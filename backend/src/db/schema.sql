-- Pedido: um por vendedor (o carrinho é dividido no checkout)
CREATE TABLE IF NOT EXISTS "Pedido" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comprador_id integer NOT NULL REFERENCES "Usuario"(id) ON DELETE CASCADE,
  vendedor_id integer NOT NULL REFERENCES "Usuario"(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'AGUARDANDO_PAGAMENTO' CONSTRAINT chk_pedido_status CHECK (status IN (
    'AGUARDANDO_PAGAMENTO', 'PAGO', 'EM_PREPARACAO', 'ENVIADO', 'PRONTO_RETIRADA', 'ENTREGUE', 'CANCELADO'
  )),
  tipo_entrega text NOT NULL CONSTRAINT chk_pedido_entrega CHECK (tipo_entrega IN ('ENTREGA', 'RETIRADA')),
  forma_pagamento text NOT NULL CONSTRAINT chk_pedido_pagamento CHECK (forma_pagamento IN ('PIX', 'CARTAO', 'BOLETO')),
  entrega_rua text, entrega_numero text, entrega_bairro text, entrega_cep text,
  entrega_cidade text, entrega_uf text,
  subtotal double precision NOT NULL,
  frete double precision NOT NULL DEFAULT 0,
  total double precision NOT NULL,
  codigo_rastreio text,
  observacao text,
  origem text NOT NULL DEFAULT 'CARRINHO' CONSTRAINT chk_pedido_origem CHECK (origem IN ('CARRINHO', 'COTACAO', 'ASSINATURA')),
  data_criacao text NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
  data_atualizacao text NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS idx_pedido_comprador ON "Pedido"(comprador_id);
