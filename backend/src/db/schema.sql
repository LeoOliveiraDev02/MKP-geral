-- Funções auxiliares das policies: SECURITY DEFINER rodam como dono das tabelas
-- (sem reaplicar RLS), o que evita recursão entre policies que se referenciam.
CREATE OR REPLACE FUNCTION app.cesta_vendedor(p_cesta integer) RETURNS integer
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS
$$ SELECT vendedor_id FROM "Cesta" WHERE id = p_cesta $$;

CREATE OR REPLACE FUNCTION app.assina_cesta(p_cesta integer, p_usuario integer) RETURNS boolean
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS
$$ SELECT EXISTS (SELECT 1 FROM "Assinatura" WHERE cesta_id = p_cesta AND cliente_id = p_usuario) $$;

CREATE OR REPLACE FUNCTION app.endereco_de_assinante(p_endereco integer, p_vendedor integer) RETURNS boolean
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS
$$ SELECT EXISTS (
     SELECT 1 FROM "Assinatura" s JOIN "Cesta" c ON c.id = s.cesta_id
     WHERE s.endereco_id = p_endereco AND c.vendedor_id = p_vendedor) $$;

-- Selo público de produtor verificado (a tabela em si só é legível pelo dono/admin).
CREATE OR REPLACE FUNCTION app.usuario_verificado(p_usuario integer) RETURNS boolean
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS
$$ SELECT EXISTS (SELECT 1 FROM "Verificacao" WHERE usuario_id = p_usuario AND status = 'APROVADA') $$;

