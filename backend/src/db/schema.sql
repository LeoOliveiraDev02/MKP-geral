CREATE TABLE IF NOT EXISTS "Imagem" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  anuncio_id integer NOT NULL REFERENCES "Anuncio"(id) ON DELETE CASCADE,
  url text NOT NULL,
