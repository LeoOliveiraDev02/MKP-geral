-- ─── Segurança: MFA e webhooks de pagamento ────────────────────────────────

-- MFA (TOTP) por usuário: obrigatório para administradores. O segredo fica
-- cifrado (AES-256-GCM, chave MFA_ENCRYPTION_KEY); `ultimo_passo` impede reusar
-- o mesmo código de 30 s (replay).
