-- ─── Sessões no servidor ────────────────────────────────────────────────────
-- Cada JWT emitido tem uma linha aqui (id = jti). Permite listar dispositivos,
-- encerrar uma sessão específica ou todas ("sair de todos os dispositivos"),
-- aplicar timeout por inatividade e derrubar tudo após troca de senha.
CREATE TABLE IF NOT EXISTS "Sessao" (
  id text PRIMARY KEY,
  usuario_id integer NOT NULL REFERENCES "Usuario"(id) ON DELETE CASCADE,
  criada_em text NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
  ultimo_uso text NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
  expira_em text NOT NULL,
  ip text,
  user_agent text,
  mfa boolean NOT NULL DEFAULT false,
  revogada_em text
);
CREATE INDEX IF NOT EXISTS idx_sessao_usuario ON "Sessao"(usuario_id);
CREATE INDEX IF NOT EXISTS idx_sessao_expira ON "Sessao"(expira_em);

-- Códigos de recuperação do MFA (uso único, guardados só como hash).
CREATE TABLE IF NOT EXISTS "MfaCodigoRecuperacao" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer NOT NULL REFERENCES "Usuario"(id) ON DELETE CASCADE,
  codigo_hash text NOT NULL,
  usado_em text
);
CREATE INDEX IF NOT EXISTS idx_mfarecuperacao_usuario ON "MfaCodigoRecuperacao"(usuario_id);

ALTER TABLE "Sessao"               ENABLE ROW LEVEL SECURITY;
ALTER TABLE "MfaCodigoRecuperacao" ENABLE ROW LEVEL SECURITY;
