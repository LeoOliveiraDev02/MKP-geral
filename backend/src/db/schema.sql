-- Recria as policies a cada boot para que alterações neste arquivo se apliquem.
DO $$
DECLARE p record;
BEGIN
  FOR p IN
    SELECT policyname, tablename FROM pg_policies
    WHERE schemaname = 'public' AND policyname LIKE 'rls_%'
  LOOP
    EXECUTE format('DROP POLICY %I ON %I', p.policyname, p.tablename);
  END LOOP;
END $$;

-- Usuario: cada um vê/edita/exclui só a própria linha. Dados de vendedor com
-- anúncio visível ficam legíveis (nome/telefone aparecem no anúncio público).
-- Criação de conta só em contexto de sistema (cadastro / login Google).
CREATE POLICY rls_usuario_select ON "Usuario" FOR SELECT USING (
  id = app.current_user_id() OR app.is_system()
  OR EXISTS (SELECT 1 FROM "Anuncio" a WHERE a.anunciante_id = "Usuario".id)
  -- contrapartes de pedido, conversa e cotação (nome no painel/chat)
  OR EXISTS (SELECT 1 FROM "Pedido" p WHERE p.comprador_id = "Usuario".id AND p.vendedor_id = app.current_user_id())
  OR EXISTS (SELECT 1 FROM "Conversa" c WHERE (c.comprador_id = "Usuario".id AND c.vendedor_id = app.current_user_id())
                                          OR (c.vendedor_id = "Usuario".id AND c.comprador_id = app.current_user_id()))
  OR EXISTS (SELECT 1 FROM "Cotacao" q WHERE q.cliente_id = "Usuario".id AND q.vendedor_id = app.current_user_id())
  -- assinantes para o produtor da cesta; produtores com cesta ativa para todos
  OR EXISTS (SELECT 1 FROM "Assinatura" s WHERE s.cliente_id = "Usuario".id AND app.cesta_vendedor(s.cesta_id) = app.current_user_id())
  OR EXISTS (SELECT 1 FROM "Cesta" c WHERE c.vendedor_id = "Usuario".id AND c.ativa)
  -- autores de conteúdo público (avaliações e perguntas mostram o nome)
  OR EXISTS (SELECT 1 FROM "Avaliacao" v WHERE v.autor_id = "Usuario".id)
  OR EXISTS (SELECT 1 FROM "Pergunta" q WHERE q.autor_id = "Usuario".id)
);
CREATE POLICY rls_usuario_insert ON "Usuario" FOR INSERT WITH CHECK (app.is_system());
CREATE POLICY rls_usuario_update ON "Usuario" FOR UPDATE
  USING (id = app.current_user_id() OR app.is_system())
  WITH CHECK (id = app.current_user_id() OR app.is_system());
CREATE POLICY rls_usuario_delete ON "Usuario" FOR DELETE
  USING (id = app.current_user_id() OR app.is_system());

